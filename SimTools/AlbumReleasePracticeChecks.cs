using System;
using System.Linq;
using Godot;

public partial class AlbumReleasePracticeChecks : Node {
	private int checks;
	private void Check(bool ok, string why) { if (!ok) throw new InvalidOperationException(why); checks++; GD.Print("ok: " + why); }
	public override void _Ready() {
		try {
			Check(!AlbumReleasePractice.CanAdvance(Genre.Classical, AlbumFormat.Standard, 1960), "generic Classical LPs do not mint commercial advance singles");
			Check(!AlbumReleasePractice.CanAdvance(Genre.TeenPop, AlbumFormat.Compilation, 1960) &&
				!AlbumReleasePractice.CanAdvance(Genre.Soul, AlbumFormat.Live, 1963), "a hit package or issued live performance is not assumed an advance campaign");
			Check(AlbumReleasePractice.CanAdvance(Genre.TraditionalPop, AlbumFormat.Standard, 1960), "adult-pop exceptions remain possible");
			Check(AlbumReleasePractice.NeedsSingleAudience(Genre.Soul, 1960, 0, 0f) &&
				!AlbumReleasePractice.NeedsSingleAudience(Genre.Soul, 1960, 1, 0f) &&
				!AlbumReleasePractice.NeedsSingleAudience(Genre.Jazz, 1960, 0, 0f) &&
				!AlbumReleasePractice.NeedsSingleAudience(Genre.Soul, 1960, 0, .999f),
				"single-led LPs usually follow demonstrated singles, while original LP and specialist programmes remain possible");
			Check(AlbumReleasePractice.AdvanceCommissionProbability(Genre.TraditionalPop, 1960) <
				AlbumReleasePractice.AdvanceCommissionProbability(Genre.TeenPop, 1960), "the existing singles orientation distinguishes commercial institutions");
			foreach (Genre genre in GenreSupplyService.GetAvailableGenres(1964))
				Check(AlbumReleasePractice.AdvanceCommissionProbability(genre, 1964, 3) is >= 0f and <= .45f, $"bounded prior for {genre}");
			foreach (Genre genre in GenreSupplyService.GetAvailableGenres(1964))
				Check(AlbumReleasePractice.AdvanceCommissionProbability(genre, 1964, 1f, 3f) == AlbumReleasePractice.AdvanceCommissionProbability(genre, 1964, 1f, 0f),
					$"the late-decade advance prior leaves 1964 {genre} unchanged");
			Check(AlbumReleasePractice.AdvanceCommissionProbability(Genre.TraditionalPop, 1966, 1f, 2f) >
				AlbumReleasePractice.AdvanceCommissionProbability(Genre.TraditionalPop, 1965, 1f, 2f) &&
				Mathf.IsEqualApprox(AlbumReleasePractice.AdvanceCommissionProbability(Genre.TraditionalPop, 1968, 1f, 2f), .30f) &&
				Mathf.IsEqualApprox(AlbumReleasePractice.AdvanceCommissionProbability(Genre.TeenPop, 1968, 1f, 2f), .30f),
				"from 1967 the late prior is orientation-free for commercial pop institutions");
			Check(AlbumReleasePractice.AdvanceCommissionProbability(Genre.Classical, 1968, 1f, 3f) == 0f &&
				AlbumReleasePractice.AdvanceCommissionProbability(Genre.Jazz, 1968, 1f, 2f) <
				AlbumReleasePractice.AdvanceCommissionProbability(Genre.TraditionalPop, 1968, 1f, 2f),
				"the late prior keeps the institution factor");
			Check(!AlbumReleasePractice.CanExtract(Genre.Jazz, 1964, 7, 1, false) &&
				!AlbumReleasePractice.CanExtract(Genre.Jazz, 1964, 9, 0, false) &&
				!AlbumReleasePractice.CanExtract(Genre.Jazz, 1964, 9, 41, false) &&
				!AlbumReleasePractice.CanExtract(Genre.Jazz, 1964, 9, 1, true) &&
				AlbumReleasePractice.CanExtract(Genre.Jazz, 1964, 9, 1, false), "later extraction requires observed, sufficiently old LP success and cannot repeat");
			Check(!AlbumReleasePractice.CanExtract(Genre.Classical, 1964, 9, 1, false), "Classical crossover is not generated by the generic extraction rule");
			float profitable = AlbumReleasePractice.IncrementalContribution(1000, 100, 200, 20, 50, 10);
			Check(profitable == 660 && AlbumReleasePractice.IncrementalContribution(1000, 100, 900, 20, 50, 10) < 0,
				"campaign, preparation, diversion and delay are charged once and can reject a nominally profitable single");
			Check(AlbumReleasePractice.IncrementalContribution(1000, 100, 200, 20, 50, 10, 700) < 0,
				"a viable independent single can beat an otherwise profitable LP campaign");
			ulong state = GameRandom.StateForChecks;
			float roll = AlbumReleasePractice.Roll("advance", "label", "artist", "album", 12);
			Check(roll == AlbumReleasePractice.Roll("advance", "label", "artist", "album", 12) &&
				roll != AlbumReleasePractice.Roll("catalogue-opportunity", "label", "artist", "album", 12) &&
				state == GameRandom.StateForChecks, "decisions are stable, domain separated and consume no global RNG");
			Check(CompetitorManager.GetApplicableEstimatorLanes(ProjectRecordRole.AlbumExtraction).SequenceEqual(new[] { RevenueEstimatorLane.AlbumExtraction }),
				"later cuts do not train the advance-promo or orphan recording forecast");
			GD.Print($"ALBUM_RELEASE_PRACTICE_CHECKS_PASS checks={checks}"); GetTree().Quit(0);
		} catch (Exception error) { GD.PrintErr("ALBUM_RELEASE_PRACTICE_CHECKS_FAIL: " + error); GetTree().Quit(1); }
	}
}
